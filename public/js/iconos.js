/**
 * Devuelve el <svg> de un ícono. Cada forma lleva pathLength="1" y --n (su orden),
 * para poder "encender" el trazo de a una con CSS.
 */
export function icono(nombre, clase = '') {
  const formas = ICONOS[nombre] ?? ICONOS.capas;
  return s(
    'svg',
    { class: `icono ${clase}`.trim(), viewBox: '0 0 24 24', 'aria-hidden': 'true', focusable: 'false' },
    formas.map(([etiqueta, atributos], n) => s(etiqueta, { ...atributos, pathLength: 1, vars: { '--n': n } })),
  );
}
